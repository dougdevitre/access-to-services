export function t(lang, key, params) {
  let str = strings[lang]?.[key] || strings.en[key] || key;
  if (params) {
    for (const [k, v] of Object.entries(params)) {
      str = str.replace(`{${k}}`, v);
    }
  }
  return str;
}
